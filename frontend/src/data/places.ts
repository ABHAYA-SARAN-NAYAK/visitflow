import { TouristPlace, CrowdLevel } from '../types';

function generateHourlyPattern(base: number, peakHour: number, variance: number): number[] {
  return Array.from({ length: 24 }, (_, h) => {
    const dist = Math.abs(h - peakHour);
    const factor = Math.max(0, 1 - dist * 0.12);
    const noise = (Math.random() - 0.5) * variance;
    return Math.max(5, Math.min(98, Math.round(base * factor + noise)));
  });
}

function generateDayPattern(weekendPeak: number): number[] {
  return [
    weekendPeak * 0.5, weekendPeak * 0.45, weekendPeak * 0.5,
    weekendPeak * 0.55, weekendPeak * 0.6, weekendPeak * 0.85, weekendPeak
  ];
}

function generateMonthPattern(peakMonth: number): number[] {
  return Array.from({ length: 12 }, (_, m) => {
    const dist = Math.min(Math.abs(m - peakMonth), 12 - Math.abs(m - peakMonth));
    return Math.max(15, Math.min(95, Math.round(75 - dist * 8 + (Math.random() - 0.5) * 10)));
  });
}

function getCrowdLevel(pct: number): CrowdLevel {
  if (pct <= 30) return 'low';
  if (pct <= 60) return 'moderate';
  if (pct <= 80) return 'high';
  return 'critical';
}

