// Simulate live crowd data updates
export function getSimulatedCrowdPct(place: TouristPlace): number {
  const hour = new Date().getHours();
  const base = place.avgCrowdByHour[hour] || 30;
  const dayOfWeek = new Date().getDay();
  const dayFactor = dayOfWeek === 0 || dayOfWeek === 6 ? 1.3 : 0.85;
  const noise = (Math.random() - 0.5) * 10;
  return Math.max(5, Math.min(98, Math.round(base * dayFactor + noise)));
}

export function getCrowdLevelFromPct(pct: number): CrowdLevel {
  if (pct <= 30) return 'low';
  if (pct <= 60) return 'moderate';
  if (pct <= 80) return 'high';
  return 'critical';
}

